// Dependency patch: give pdfkit a "workerd" export condition, so the Cloudflare
// Worker bundle gets pdfkit's browser build with its built-in fonts registered.
//
// Runs automatically on `npm install` / `npm ci` (package.json "postinstall") and
// again before every Worker build (the deploy/preview/upload scripts), so it also
// applies when installs run with --ignore-scripts. Idempotent.
//
// Why it's needed
//   OpenNext bundles the Worker with esbuild: platform "node", conditions
//   ["workerd"]. pdfkit 0.20.1 exports
//     ".": { "node": { "import": pdfkit.node.mjs, "require": pdfkit.js },
//            "default": pdfkit.browser.mjs }
//   so esbuild picks the Node build ("node" is active on platform node). That
//   build loads pdfkit's 14 built-in fonts with a runtime
//   createRequire(import.meta.url)("#standard-fonts/…"), which can't be bundled,
//   so the first PDF on Workers failed with
//   `No such module "#standard-fonts/Helvetica"`.
//
// What it changes (inside node_modules/pdfkit only)
//   1. adds js/pdfkit.workerd.mjs: imports the browser build (no filesystem or
//      Node streams), registers the 14 built-in fonts with registerStdFonts(),
//      and re-exports everything. Registering inside pdfkit means every importer
//      (react-pdf included) gets a ready pdfkit before its own code runs.
//      Registering from app code instead raced react-pdf's font store (Turbopack
//      makes that code an async module) and left unhandled rejections.
//   2. package.json: ".": { "workerd": "./js/pdfkit.workerd.mjs", "node": {…unchanged}, "default": … }
//   esbuild (and Node) take the first matching key in object order, so the Worker
//   bundle (condition "workerd") gets the wrapper, while Node (next dev/start,
//   scripts, Vercel) never sets "workerd" and keeps the Node build exactly as before.
//
// Safeguards
//   Only the exact, known pdfkit layout is patched. Any other version or export
//   shape fails the install with an explanation, rather than shipping a Worker
//   whose PDFs break. tests/pdf/pdfkit-workerd-patch.test.ts checks the patch is
//   applied and that esbuild resolves pdfkit to the wrapper for the Worker.

import { existsSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

export const SUPPORTED_VERSION = "0.20.1";
export const BROWSER_BUILD = "./js/pdfkit.browser.mjs";
export const WORKERD_ENTRY = "./js/pdfkit.workerd.mjs";
export const STANDARD_FONTS = [
  "Courier",
  "CourierBold",
  "CourierBoldOblique",
  "CourierOblique",
  "Helvetica",
  "HelveticaBold",
  "HelveticaBoldOblique",
  "HelveticaOblique",
  "Symbol",
  "TimesBold",
  "TimesBoldItalic",
  "TimesItalic",
  "TimesRoman",
  "ZapfDingbats",
];

const ORIGINAL_MAIN_EXPORT = {
  node: { import: "./js/pdfkit.node.mjs", require: "./js/pdfkit.js" },
  default: BROWSER_BUILD,
};
/** The first version of this patch pointed "workerd" straight at the browser build; it is upgraded in place. */
const PREVIOUS_MAIN_EXPORT = { workerd: BROWSER_BUILD, ...ORIGINAL_MAIN_EXPORT };
const PATCHED_MAIN_EXPORT = { workerd: WORKERD_ENTRY, ...ORIGINAL_MAIN_EXPORT };

export const WORKERD_ENTRY_SOURCE = [
  "// GENERATED by scripts/patch-pdfkit-workerd.mjs (Aabhar Studio). Cloudflare Workers only.",
  "// pdfkit's browser build with its 14 built-in fonts registered before any importer runs.",
  'import { registerStdFonts } from "./pdfkit.browser.mjs";',
  ...STANDARD_FONTS.map((f) => `import ${f}Font from "./standard-fonts/${f}.mjs";`),
  "",
  `registerStdFonts(${STANDARD_FONTS.map((f) => `${f}Font`).join(", ")});`,
  "",
  'export * from "./pdfkit.browser.mjs";',
  'export { default } from "./pdfkit.browser.mjs";',
  "",
].join("\n");

const same = (a, b) => JSON.stringify(a) === JSON.stringify(b);

/**
 * Patches the pdfkit package in `pkgDir`.
 * @returns {"patched" | "already-patched" | "not-installed"}
 * @throws if pdfkit isn't the exact supported version and layout.
 */
export function patchPdfkit(pkgDir) {
  const pkgPath = path.join(pkgDir, "package.json");
  if (!existsSync(pkgPath)) return "not-installed";

  const raw = readFileSync(pkgPath, "utf8");
  const pkg = JSON.parse(raw);
  const main = pkg.exports?.["."];

  if (pkg.name !== "pdfkit" || pkg.version !== SUPPORTED_VERSION) {
    throw new Error(
      `patch-pdfkit-workerd: expected pdfkit ${SUPPORTED_VERSION}, found ${pkg.name}@${pkg.version}. ` +
        `Check that pdfkit's new exports still need this patch, then update SUPPORTED_VERSION and the expected layout in scripts/patch-pdfkit-workerd.mjs.`,
    );
  }
  for (const f of [BROWSER_BUILD, ...STANDARD_FONTS.map((n) => `./js/standard-fonts/${n}.mjs`)]) {
    if (!existsSync(path.join(pkgDir, f))) throw new Error(`patch-pdfkit-workerd: ${f} is missing from pdfkit ${pkg.version}.`);
  }
  const exportsPatched = same(main, PATCHED_MAIN_EXPORT);
  if (!exportsPatched && !same(main, ORIGINAL_MAIN_EXPORT) && !same(main, PREVIOUS_MAIN_EXPORT)) {
    throw new Error(`patch-pdfkit-workerd: pdfkit's "." export has an unexpected shape: ${JSON.stringify(main)}. Review the patch.`);
  }
  const entryPath = path.join(pkgDir, WORKERD_ENTRY);
  const entryOk = existsSync(entryPath) && readFileSync(entryPath, "utf8") === WORKERD_ENTRY_SOURCE;
  if (exportsPatched && entryOk) return "already-patched";

  // Entry file first, exports last: "workerd" never points at a missing file.
  if (!entryOk) writeFileSync(entryPath, WORKERD_ENTRY_SOURCE);
  if (!exportsPatched) {
    pkg.exports["."] = PATCHED_MAIN_EXPORT;
    // Keep pdfkit's own formatting (2-space JSON) and line ending.
    const eol = raw.includes("\r\n") ? "\r\n" : "\n";
    writeFileSync(pkgPath, JSON.stringify(pkg, null, 2).replace(/\n/g, eol) + eol);
  }
  return "patched";
}

// CLI: node scripts/patch-pdfkit-workerd.mjs
if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
  try {
    const result = patchPdfkit(path.join(root, "node_modules", "pdfkit"));
    if (result === "patched") console.log(`patch-pdfkit-workerd: pdfkit ${SUPPORTED_VERSION} patched ("workerd" → browser build with built-in fonts registered).`);
  } catch (err) {
    console.error(err instanceof Error ? err.message : err);
    process.exit(1);
  }
}
