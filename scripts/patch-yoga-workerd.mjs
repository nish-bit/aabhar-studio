// Dependency patch: let yoga-layout 3.2.1 (react-pdf's layout engine) run on
// Cloudflare Workers.
//
// Runs on `npm install` / `npm ci` (package.json "postinstall") and before every
// Worker build (deploy/preview/upload scripts). Idempotent.
//
// Why it's needed
//   yoga-layout ships its WebAssembly as a base64 string inside
//   dist/binaries/yoga-wasm-base64-esm.js and compiles it at runtime with
//   WebAssembly.instantiate(bytes). Workers forbid compiling WebAssembly from
//   bytes at runtime ("Wasm code generation disallowed by embedder"); a Worker
//   must ship WebAssembly as a module that Cloudflare compiles at upload time.
//
// What it adds (inside node_modules/yoga-layout only; existing files untouched)
//   1. dist/binaries/yoga.wasm        the exact bytes of the embedded base64 binary
//   2. dist/src/load.workerd.js       loadYoga() that imports yoga.wasm as a
//                                     precompiled WebAssembly.Module and gives it
//                                     to Emscripten's documented instantiateWasm hook,
//                                     so nothing is compiled at runtime
//   3. package.json exports["./load"] gains a first "workerd" entry pointing at (2);
//      every other condition still gets the original dist/src/load.js.
//
//   OpenNext bundles the Worker with esbuild conditions ["workerd"], so react-pdf's
//   `import "yoga-layout/load"` selects (2). OpenNext's wrangler-externals plugin
//   leaves the `.wasm` import for Wrangler, whose default module rules upload
//   `**/*.wasm` as a CompiledWasm module (default export: WebAssembly.Module).
//   Node never sets "workerd", so Node keeps the original loader unchanged.
//
// Safeguards
//   Only yoga-layout 3.2.1 with the exact expected layout is patched; anything else
//   fails the install with an explanation. tests/pdf/yoga-workerd-patch.test.ts
//   checks the patch and the loader.

import { existsSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

export const SUPPORTED_VERSION = "3.2.1";
const EMBEDDED_LOADER = "dist/binaries/yoga-wasm-base64-esm.js";
const ORIGINAL_LOAD = "./dist/src/load.js";
export const WASM_FILE = "dist/binaries/yoga.wasm";
export const WORKERD_LOADER = "dist/src/load.workerd.js";
const ORIGINAL_EXPORTS = { ".": "./dist/src/index.js", "./load": ORIGINAL_LOAD };
const PATCHED_EXPORTS = { ".": "./dist/src/index.js", "./load": { workerd: `./${WORKERD_LOADER}`, default: ORIGINAL_LOAD } };

export const WORKERD_LOADER_SOURCE = `// GENERATED by scripts/patch-yoga-workerd.mjs (Aabhar Studio). Cloudflare Workers only.
// Same API as ./load.js, but Yoga's WebAssembly comes from ../binaries/yoga.wasm,
// which Wrangler uploads as a precompiled module, instead of being compiled from
// the embedded base64 at runtime (which Workers forbid).
import loadYogaImpl from "../binaries/yoga-wasm-base64-esm.js";
import yogaWasmModule from "../binaries/yoga.wasm";
import wrapAssembly from "./wrapAssembly.js";

export async function loadYoga() {
  if (!(yogaWasmModule instanceof WebAssembly.Module)) {
    throw new Error("yoga-layout (workerd): yoga.wasm was not bundled as a WebAssembly.Module");
  }
  let fail;
  const failed = new Promise((_, reject) => {
    fail = reject;
  });
  const module = loadYogaImpl({
    // Emscripten's hook: instantiate the precompiled module, hand the instance back.
    // Returning {} tells Emscripten the exports arrive asynchronously.
    instantiateWasm(imports, receiveInstance) {
      WebAssembly.instantiate(yogaWasmModule, imports).then((instance) => receiveInstance(instance, yogaWasmModule), fail);
      return {};
    },
  });
  // An instantiation failure would otherwise leave Emscripten waiting forever.
  return wrapAssembly(await Promise.race([module, failed]));
}

export * from "./generated/YGEnums.js";
`;

const same = (a, b) => JSON.stringify(a) === JSON.stringify(b);

/** The binary embedded in yoga-wasm-base64-esm.js (exactly one `H="data:…;base64,…"` assignment). */
export function extractWasm(embeddedLoaderSource) {
  const matches = [...embeddedLoaderSource.matchAll(/H="data:application\/octet-stream;base64,([A-Za-z0-9+/=]+)"/g)];
  if (matches.length !== 1) throw new Error(`patch-yoga-workerd: expected one embedded wasm binary, found ${matches.length}.`);
  const bytes = Buffer.from(matches[0][1], "base64");
  if (bytes.subarray(0, 4).toString("latin1") !== "\0asm") throw new Error("patch-yoga-workerd: the embedded binary isn't WebAssembly.");
  return bytes;
}

/**
 * Patches the yoga-layout package in `pkgDir`.
 * @returns {"patched" | "already-patched" | "not-installed"}
 * @throws if yoga-layout isn't the exact supported version and layout.
 */
export function patchYoga(pkgDir) {
  const pkgPath = path.join(pkgDir, "package.json");
  if (!existsSync(pkgPath)) return "not-installed";
  const raw = readFileSync(pkgPath, "utf8");
  const pkg = JSON.parse(raw);

  if (pkg.name !== "yoga-layout" || pkg.version !== SUPPORTED_VERSION) {
    throw new Error(
      `patch-yoga-workerd: expected yoga-layout ${SUPPORTED_VERSION}, found ${pkg.name}@${pkg.version}. ` +
        `Check whether the new version still compiles WebAssembly at runtime, then update scripts/patch-yoga-workerd.mjs.`,
    );
  }
  for (const f of [EMBEDDED_LOADER, "dist/src/load.js", "dist/src/wrapAssembly.js", "dist/src/generated/YGEnums.js"]) {
    if (!existsSync(path.join(pkgDir, f))) throw new Error(`patch-yoga-workerd: ${f} is missing from yoga-layout ${pkg.version}.`);
  }
  const wasm = extractWasm(readFileSync(path.join(pkgDir, EMBEDDED_LOADER), "utf8"));

  const exportsPatched = same(pkg.exports, PATCHED_EXPORTS);
  if (!exportsPatched && !same(pkg.exports, ORIGINAL_EXPORTS)) {
    throw new Error(`patch-yoga-workerd: yoga-layout's exports have an unexpected shape: ${JSON.stringify(pkg.exports)}.`);
  }
  const wasmPath = path.join(pkgDir, WASM_FILE);
  const loaderPath = path.join(pkgDir, WORKERD_LOADER);
  const wasmOk = existsSync(wasmPath) && readFileSync(wasmPath).equals(wasm);
  const loaderOk = existsSync(loaderPath) && readFileSync(loaderPath, "utf8") === WORKERD_LOADER_SOURCE;
  if (exportsPatched && wasmOk && loaderOk) return "already-patched";

  // Files first, exports last: the "workerd" entry never points at a missing loader.
  if (!wasmOk) writeFileSync(wasmPath, wasm);
  if (!loaderOk) writeFileSync(loaderPath, WORKERD_LOADER_SOURCE);
  if (!exportsPatched) {
    pkg.exports = PATCHED_EXPORTS;
    const eol = raw.includes("\r\n") ? "\r\n" : "\n";
    writeFileSync(pkgPath, JSON.stringify(pkg, null, 2).replace(/\n/g, eol) + eol);
  }
  return "patched";
}

// CLI: node scripts/patch-yoga-workerd.mjs
if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
  try {
    const result = patchYoga(path.join(root, "node_modules", "yoga-layout"));
    if (result === "patched") console.log(`patch-yoga-workerd: yoga-layout ${SUPPORTED_VERSION} patched ("workerd" → precompiled yoga.wasm loader).`);
  } catch (err) {
    console.error(err instanceof Error ? err.message : err);
    process.exit(1);
  }
}
